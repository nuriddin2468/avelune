/**
 * The fill of a progress bar: `accent` while the work goes on, `success` once it has finished, `danger` when it failed.
 *
 * @beta
 */
export type AveProgressVariant = 'accent' | 'success' | 'danger';

/**
 * The thickness of a progress bar: `sm` 4px, `md` 8px (default).
 *
 * @beta
 */
export type AveProgressSize = 'sm' | 'md';
